# Parameter range
r_values = np.linspace(2.5, 4.0, 3000)

x0 = 0.213
transient = 1000
iterations = 3000

lyapunov = []

for r in r_values:
    x = x0

    # Discard transient
    for _ in range(transient):
        x = r * x * (1 - x)

    # Calculate Lyapunov exponent
    total = 0.0

    for _ in range(iterations):
        derivative = abs(r * (1 - 2 * x))

        if derivative == 0:
            total = -np.inf
            break

        total += np.log(derivative)
        x = r * x * (1 - x)

    lyapunov.append(total / iterations)

lyapunov = np.array(lyapunov)

# Plot
plt.figure(figsize=(12, 6))

