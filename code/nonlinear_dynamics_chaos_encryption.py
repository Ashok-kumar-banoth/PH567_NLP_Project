import matplotlib.pyplot as plt
import numpy as np
import time

test_messages = [
    "CHAOS",
    "LOGISTICMAP",
    "NONLINEARDYNAMICS",
    "ENCRYPTION"
]

all_counts = []

print("ENCRYPTION TEST RESULTS")
print("-" * 55)

for message in test_messages:
    start = time.perf_counter()

    encrypted = encrypt(message, 0.213)
    decrypted = decrypt(encrypted, 0.213)

    elapsed = time.perf_counter() - start

    all_counts.extend(encrypted)

    print("Original :", message)
    print("Ciphertext:", encrypted)
    print("Recovered :", decrypted)
    print("Success   :", message == decrypted)
    print("Time (s)  :", round(elapsed, 6))
    print("-" * 55)


