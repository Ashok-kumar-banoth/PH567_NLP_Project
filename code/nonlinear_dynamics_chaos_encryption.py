import numpy as np

# Logistic Map
def logistic_step(x, r=4.0):
    return r * x * (1 - x)


# Divide state space into character intervals
characters = "ABCDEFGHIJKLMNOPQRSTUVWXYZ"
intervals = np.linspace(0, 1, len(characters) + 1)

char_to_interval = {
    char: i for i, char in enumerate(characters)
}


# Encryption
def encrypt(message, x0, r=4.0):
    x = x0
    ciphertext = []

    for char in message.upper():
        if char not in char_to_interval:
            continue

        target = char_to_interval[char]
        count = 0

        # Iterate until target interval is reached
        while True:
            x = logistic_step(x, r)
            count += 1

            if intervals[target] <= x < intervals[target + 1]:
                break

            if count > 100000:
                raise RuntimeError("Target interval not reached")

        ciphertext.append(count)

    return ciphertext


# Decryption
def decrypt(ciphertext, x0, r=4.0):
    x = x0
    recovered = []

    for count in ciphertext:
        for _ in range(count):
            x = logistic_step(x, r)

        index = np.searchsorted(intervals, x, side="right") - 1
        index = min(index, len(characters) - 1)

        recovered.append(characters[index])

    return "".join(recovered)


